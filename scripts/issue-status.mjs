import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const run = (cmd) => execSync(cmd, { encoding: 'utf8', maxBuffer: 1 << 26 });
const issues = JSON.parse(run('gh issue list --state all --limit 200 --json number,title,state,body,labels'));
const log = run('git log --format=%B main');
const fixed = new Set([...log.matchAll(/Fixes #(\d+)/g)].map((m) => +m[1]));
const referenced = new Set([...log.matchAll(/Refs #(\d+)/g)].map((m) => +m[1]));

const stateOf = (issue) => {
  if (issue.state === 'CLOSED') return 'closed';
  if (fixed.has(issue.number) || issue.labels.some((label) => label.name === 'fixed-on-main')) return 'done';
  if (issue.labels.some((label) => label.name === 'parked')) return 'parked';
  if (referenced.has(issue.number)) return 'partial';
  return 'todo';
};

const lines = ['graph LR'];
for (const issue of issues.sort((a, b) => a.number - b.number)) {
  lines.push(`  i${issue.number}["#${issue.number} ${issue.title.replace(/"/g, "'")}"]:::${stateOf(issue)}`);
  const blockedBy = issue.body.split('## Blocked by')[1] ?? '';
  for (const [, blocker] of blockedBy.matchAll(/- #(\d+)/g)) lines.push(`  i${blocker} --> i${issue.number}`);
}
lines.push(
  '  classDef closed fill:#1f6f3f,color:#fff,stroke:#1f6f3f',
  '  classDef done fill:#2e9e5b,color:#fff,stroke:#2e9e5b',
  '  classDef partial fill:#d4a017,color:#000,stroke:#d4a017',
  '  classDef parked fill:#7a4fbf,color:#fff,stroke:#7a4fbf',
  '  classDef todo fill:#888,color:#fff,stroke:#888',
);

const count = (state) => issues.filter((issue) => stateOf(issue) === state).length;
writeFileSync(
  'STATUS.md',
  `# Issue status

Generated by \`node scripts/issue-status.mjs\` from GitHub issues and the \`Fixes\` / \`Refs\` lines of commits on \`main\`. An arrow points from a blocker to the issue it blocks.

closed ${count('closed')}, done on main ${count('done')}, partial ${count('partial')}, parked ${count('parked')}, not started ${count('todo')}

\`\`\`mermaid
${lines.join('\n')}
\`\`\`
`,
);
