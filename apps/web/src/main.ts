import './legacyStorage';
import { createApp, watchEffect } from 'vue';
import { installUiKit } from '@ui/kit';
import './app.css';
import './motion/statusAnimation.css';
import { installKeymap } from './commands/dispatcher';
import { t } from './i18n';
import { setMotionEnabled } from './motion';
import { installStatusAnimation } from './motion/statusAnimation';
import { loadHostPlatform } from './platform';
import { installAppearance } from './settings/appearance';
import { installBerthIdleSync } from './settings/berthIdle';
import { useSettings } from './settings/store';
import { setTranslator } from './settings/translate';
import WorkspaceView from './WorkspaceView.vue';

setTranslator(t);
void loadHostPlatform();
const app = createApp(WorkspaceView);
installUiKit(app);
installAppearance();
installBerthIdleSync();
const { values } = useSettings();
watchEffect(() => setMotionEnabled(values.value['ui.animations']));
installStatusAnimation(() => (values.value['ui.animations'] ? values.value['ui.statusAnimation'] : 'off'));
installKeymap();
app.mount('#app');
